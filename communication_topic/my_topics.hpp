#pragma once

#include "topic.hpp"

/*******************************************************************************
 * ============================================================================
 *                         Topic 实例定义文件
 * ============================================================================
 *
 * 【文件用途】
 *   集中定义所有 Topic 的全局静态实例，类似于 PX4 uORB 中的 ORB_DEFINE 宏。
 *
 * 【设计原则】
 *   1. 所有 Topic 定义在一个地方，便于管理和查找
 *   2. 使用 inline 变量（C++17），避免多重定义问题
 *   3. 放在 orb 命名空间中，避免全局命名污染
 *
 * 【如何添加新 Topic】
 *   1. 在本文件中定义数据结构（或在其他头文件中定义后 include）
 *   2. 在 orb 命名空间中添加 Topic 实例
 *
 *   示例：
 *   // 定义数据结构
 *   struct ChassisState {
 *       float vx, vy, omega;
 *       uint32_t timestamp;
 *   };
 *
 *   // 定义 Topic 实例
 *   inline Topic<ChassisState> chassis_state;
 *
 * 【Topic 类型选择指南】
 *   +------------------+--------------------------------+------------------------+
 *   | Topic 类型       | 适用场景                        | 特点                   |
 *   +------------------+--------------------------------+------------------------+
 *   | Topic<T>         | 只关心最新值                    | 简单、低开销           |
 *   |                  | 状态信息、控制指令              | 可能丢失中间数据       |
 *   +------------------+--------------------------------+------------------------+
 *   | RingTopic<T,D>   | 需要处理每一条数据              | 环形缓冲、保留历史     |
 *   |                  | 传感器数据、日志等              | 内存占用 = D * sizeof(T)|
 *   +------------------+--------------------------------+------------------------+
 *   | MultiTopic<T,N>  | 同类型多实例                    | 数组形式、索引访问     |
 *   |                  | 多个 IMU、多个电机等            |                        |
 *   +------------------+--------------------------------+------------------------+
 *
 ******************************************************************************/

namespace orb {

/*******************************************************************************
 * 数据结构定义
 * ----------------------------------------------------------------------------
 * 这里定义 Topic 承载的数据类型。
 * 建议：
 *   - 使用 POD (Plain Old Data) 类型，便于拷贝
 *   - 保持结构体紧凑，避免填充浪费
 *   - 如果需要时间戳，可以添加 timestamp 字段
 ******************************************************************************/

/**
 * @brief IMU 传感器数据
 *
 * 包含三轴加速度和三轴角速度。
 * 坐标系约定：
 *   - X: 前
 *   - Y: 左
 *   - Z: 上
 *
 * 单位：
 *   - accel: m/s^2
 *   - gyro: rad/s
 */
struct ImuData {
    float accel[3];  // 三轴加速度 [x, y, z]
    float gyro[3];   // 三轴角速度 [x, y, z]
};

/**
 * @brief 电机控制指令
 *
 * 四个电机的占空比指令。
 *
 * 单位：
 *   - duty: 归一化占空比，范围 [-1.0, 1.0]
 */
struct MotorCmd {
    float duty[4];  // 四个电机的占空比 [0..3]
};

/*******************************************************************************
 * Topic 实例定义
 * ----------------------------------------------------------------------------
 * 使用 C++17 inline 变量，在头文件中定义全局实例。
 *
 * 命名约定：
 *   - 使用小写 + 下划线
 *   - 名称应该清晰表达 Topic 的内容
 ******************************************************************************/

/**
 * @brief IMU 数据 Topic（多实例 + 环形缓冲）
 *
 * 配置说明：
 *   - MultiTopic<..., 2>: 支持 2 个 IMU 实例
 *   - RingTopic<ImuData, 4>: 每个 IMU 保留 4 条历史数据
 *
 * 使用示例：
 *   // 发布者（IMU 驱动中断）
 *   orb::imu[0].publish(imu_data);
 *
 *   // 订阅者（姿态解算任务）
 *   RingSub<ImuData, 4> imu_sub(orb::imu[0]);
 *   ImuData data;
 *   while (imu_sub.copy(data)) {
 *       // 处理每一条 IMU 数据
 *   }
 */
inline MultiTopic<RingTopic<ImuData, 4>, 2> imu;

/**
 * @brief 电机控制指令 Topic
 *
 * 配置说明：
 *   - 使用简单的 Topic<T>，只关心最新指令
 *   - 如果控制器来不及读取，旧指令被覆盖（期望行为）
 *
 * 使用示例：
 *   // 发布者（控制器任务）
 *   MotorCmd cmd = {.duty = {0.5f, 0.5f, 0.5f, 0.5f}};
 *   orb::motor_cmd.publish(cmd);
 *
 *   // 订阅者（电机驱动任务）
 *   Subscription<MotorCmd> cmd_sub(orb::motor_cmd);
 *   MotorCmd cmd;
 *   if (cmd_sub.copy(cmd)) {
 *       apply_to_motors(cmd);
 *   }
 */
inline Topic<MotorCmd> motor_cmd;

} // namespace orb
